@pytest.fixture(autouse=True)
def worker_uses_test_storage(
    monkeypatch: pytest.MonkeyPatch, settings: Settings, object_store: ObjectStore
) -> Iterator[None]:
    monkeypatch.setattr(processing, "get_settings", lambda: settings)
    monkeypatch.setattr(processing, "get_object_store", lambda: object_store)
    yield


@pytest.fixture
def speaker_id(client: TestClient, make_user: MakeUser, db: Session) -> str:
    act_as(client, make_user("asha", "contributor"))
    speaker = own_speaker(client)
    give_consent(client, db, speaker)
    return speaker


def submit_audio(client: TestClient, speaker_id: str, content: bytes) -> uuid.UUID:
    """Uploads `content` as a new submission and submits it; returns the recording ID."""
    draft = create_draft(client, speaker_id)
    response = upload(client, draft["id"], content)
    assert response.status_code == 202, response.text
    assert client.post(f"{SUBMISSIONS}/{draft['id']}/submit").status_code == 200
    return uuid.UUID(response.json()["recording_id"])


def run_jobs(engine: Engine) -> None:
    while queue.process_one(engine, "test-worker", 60):
        pass


def fetch(db: Session, recording_id: uuid.UUID) -> tuple[Recording, Submission]:
    db.expire_all()
    recording = db.get_one(Recording, recording_id)
    return recording, db.get_one(Submission, recording.submission_id)


@pytest.mark.parametrize("container", ENCODINGS)
def test_valid_recordings_are_promoted_unchanged(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    object_store: ObjectStore,
    tmp_path: Path,
    container: str,
) -> None:
    rate = 48000 if container in ("webm", "ogg") else 44100  # Opus has no 44.1 kHz
    content = make_audio(tmp_path / "input", container, seconds=3, rate=rate, channels=2)
    recording_id = submit_audio(client, speaker_id, content)
    run_jobs(engine)

    recording, submission = fetch(db, recording_id)
    assert recording.upload_status == "promoted"
    assert recording.channels == 2
    assert recording.sample_rate_hz == rate
    assert recording.duration_ms is not None and 2900 <= recording.duration_ms <= 3100
    assert recording.is_lossy_source is (container not in ("wav", "flac"))
    assert recording.bit_depth == (16 if container in ("wav", "flac") else None)
    assert recording.validation_errors is None
    key = recording.original_object_key
    assert object_store.sha256_of(Bucket.ORIGINALS, key) == recording.sha256_original
    assert object_store.head(Bucket.QUARANTINE, key) is None  # cleaned up
    assert submission.status == "processing"  # analysis and review steps follow

    run = db.scalars(select(ProcessingRun).where(ProcessingRun.job_type == "audio.validate")).one()
    assert run.status == "succeeded"
    assert run.tool_versions["ffmpeg"].startswith("ffmpeg version")
    assert run.input_sha256 == recording.sha256_original


def test_damaged_recordings_are_rejected_with_a_code(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    object_store: ObjectStore,
    tmp_path: Path,
) -> None:
    whole = make_audio(tmp_path / "input", "webm", seconds=5)
    recording_id = submit_audio(client, speaker_id, whole[: len(whole) // 2])
    run_jobs(engine)

    recording, submission = fetch(db, recording_id)
    assert recording.upload_status == "rejected_invalid"
    assert recording.validation_errors == {"code": "corrupt_audio", "reason": "decode_errors"}
    assert submission.status == "rejected_invalid"
    key = recording.original_object_key
    assert object_store.head(Bucket.ORIGINALS, key) is None
    assert object_store.head(Bucket.QUARANTINE, key) is None


def test_a_file_that_only_starts_like_audio_is_rejected(
    client: TestClient, speaker_id: str, engine: Engine, db: Session
) -> None:
    disguised = b"\x1a\x45\xdf\xa3" + b"not a recording " * 100
    recording_id = submit_audio(client, speaker_id, disguised)
    run_jobs(engine)

    recording, submission = fetch(db, recording_id)
    assert recording.upload_status == "rejected_invalid"
    assert recording.validation_errors is not None
    assert recording.validation_errors["code"] in ("unsupported_format", "corrupt_audio")
    assert submission.status == "rejected_invalid"


def test_recordings_over_the_length_limit_are_rejected(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    settings: Settings,
    tmp_path: Path,
) -> None:
    settings.max_audio_seconds = 2
    recording_id = submit_audio(client, speaker_id, make_audio(tmp_path / "a", "ogg", seconds=4))
    run_jobs(engine)

    recording, _ = fetch(db, recording_id)
    assert recording.validation_errors == {"code": "out_of_range", "reason": "too_long"}


def test_validating_again_changes_nothing(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    object_store: ObjectStore,
    tmp_path: Path,
) -> None:
    recording_id = submit_audio(client, speaker_id, make_audio(tmp_path / "a", "flac"))
    run_jobs(engine)
    before, _ = fetch(db, recording_id)

    queue.enqueue(db, "audio.validate", target_type="recording", target_id=recording_id)
    db.commit()
    run_jobs(engine)

    after, _ = fetch(db, recording_id)
    assert after.upload_status == "promoted"
    assert after.duration_ms == before.duration_ms
    key = after.original_object_key
    assert object_store.sha256_of(Bucket.ORIGINALS, key) == after.sha256_original
    summaries = db.scalars(
        select(ProcessingRun.output_summary)
        .where(ProcessingRun.job_type == "audio.validate")
        .order_by(ProcessingRun.id)
    ).all()
    assert summaries[-1] == {"skipped": "promoted"}


def test_a_copy_left_by_an_interrupted_attempt_is_reused(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    object_store: ObjectStore,
    tmp_path: Path,
) -> None:
    content = make_audio(tmp_path / "a", "mp3")
    recording_id = submit_audio(client, speaker_id, content)
    recording, _ = fetch(db, recording_id)
    with (tmp_path / "a").open("rb") as file:
        object_store.put(Bucket.ORIGINALS, recording.original_object_key, file)
    run_jobs(engine)

    recording, _ = fetch(db, recording_id)
    assert recording.upload_status == "promoted"


def test_a_changed_quarantine_file_is_not_promoted(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    object_store: ObjectStore,
    tmp_path: Path,
) -> None:
    recording_id = submit_audio(client, speaker_id, make_audio(tmp_path / "a", "wav"))
    recording, _ = fetch(db, recording_id)
    make_audio(tmp_path / "b", "wav", seconds=1)
    with (tmp_path / "b").open("rb") as file:
        object_store.delete(Bucket.QUARANTINE, recording.original_object_key)
        object_store.put(Bucket.QUARANTINE, recording.original_object_key, file)
    run_jobs(engine)

    job = db.scalars(select(Job).where(Job.job_type == "audio.validate")).one()
    assert (job.status, job.last_error_code) == ("failed", "checksum_mismatch")
    recording, _ = fetch(db, recording_id)
    assert recording.upload_status == "quarantined"
    assert object_store.head(Bucket.ORIGINALS, recording.original_object_key) is None
